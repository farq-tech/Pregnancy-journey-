/** First and last week that have authored content. */
export const MIN_CONTENT_WEEK = 4;
export const MAX_CONTENT_WEEK = 40;

/**
 * Content for a gestational week. Weeks below 4 fall back to the "pre" stage
 * copy; weeks past 40 clamp to week 40, matching the prototype's `wc()`.
 */
export function weekContent(week: number): WeekContent {
  if (week < MIN_CONTENT_WEEK) {
    return {
      size: '',
      compare: '',
      weight: '',
      appearance: '',
      symptoms: [],
      milestones: [],
      ...PRE_WEEKS,
    } as WeekContent;
  }
  const clamped = Math.min(Math.max(week, MIN_CONTENT_WEEK), MAX_CONTENT_WEEK);
  return WEEKS[String(clamped) as keyof typeof WEEKS] as WeekContent;
}
