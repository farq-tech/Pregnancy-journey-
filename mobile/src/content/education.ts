/**
 * The educational layer of the journey.
 *
 * `pregnancyData.ts` answers "what is happening this week". This file answers
 * the three questions that turn a tracker into a companion:
 *
 *   - **شيقة**  — one memorable fact per week, so opening the app is a small
 *     reward rather than a chore.
 *   - **تثقيفية** — nutrition, movement, comfort measures and myth-busting,
 *     written as *understanding*, never as a prescription.
 *   - **عائلية** — one concrete thing the partner or the family can do that
 *     week. A pregnancy is carried by one person and lived by a household.
 *
 * The editorial rules are the same as the rest of the app and are not
 * negotiable:
 *   1. Nothing here is personal medical advice. Anything that could vary by
 *      case is phrased as "قد" / "بحسب الطبيب", and every screen that renders
 *      this content also renders `DISCLAIMER`.
 *   2. No numbers are invented. Where a figure is well established (e.g. the
 *      400 mcg folic-acid figure published by ACOG/NHS) it is attributed; where
 *      it varies, no figure is given at all.
 *   3. Myths are only listed when the correction is uncontroversial across
 *      ACOG, NHS and Mayo Clinic. Anything genuinely debated is left out.
 *
 * Sources: ACOG, NHS Pregnancy, Mayo Clinic — the same three the week content
 * is drawn from. Last reviewed with `PREGNANCY_DATA.lastReviewed`.
 */

