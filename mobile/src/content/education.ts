/** The insight for a week, clamped to the range that has authored content. */
export function insightForWeek(week: number): WeekInsight {
  const clamped = Math.min(Math.max(week, MIN_CONTENT_WEEK), MAX_CONTENT_WEEK);
  return WEEK_INSIGHTS[clamped] ?? WEEK_INSIGHTS[MIN_CONTENT_WEEK];
}

